export function media({ cat, role, tag, orientation, kind } = {}) {
  return MEDIA.filter((m) =>
    (!cat || m.cat === cat) &&
    (!role || m.role === role) &&
    (!kind || m.kind === kind) &&
    (!orientation || m.orientation === orientation) &&
    (!tag || (m.tags || []).includes(tag))
  ).sort((a, b) => (b.score || 0) - (a.score || 0));
}

export function one(filter) { return media(filter)[0] || null; }
